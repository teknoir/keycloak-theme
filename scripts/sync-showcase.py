#!/usr/bin/env python3
"""sync-showcase: put the platform showcase page under the sign-in landing.

  scripts/sync-showcase.py [SRC]

SRC is the showcase source (showcase/teknoir-platform.src.html in the Teknoir workspace). With SRC the
file is first copied to showcase/teknoir-platform.src.html in this repo, so the generated files can
always be rebuilt from what is checked in; without SRC the checked-in copy is used.

Writes two generated files (never edit them by hand):

  themes/teknoir-theme/login/tn-showcase.ftl          every showcase section after the hero, plus the
                                                      footer; template.ftl includes it on the landing
  themes/teknoir-theme/login/resources/css/showcase.css
                                                      the showcase styles, every rule scoped to .tn-sc so
                                                      they cannot touch the sign-in card or PatternFly

The showcase hero is not copied: the landing's own hero (doors, mark and rails into the sign-in card)
replaces it. The markup is wrapped in <#noparse>; the @@LOGO@@ and @@MARK@@ placeholders become images
from the theme's resources.
"""
from __future__ import annotations

import hashlib
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COPY = os.path.join(ROOT, "showcase", "teknoir-platform.src.html")
LOGIN = os.path.join(ROOT, "themes", "teknoir-theme", "login")
OUT_FTL = os.path.join(LOGIN, "tn-showcase.ftl")
OUT_CSS = os.path.join(LOGIN, "resources", "css", "showcase.css")
SCOPE = ".tn-sc"

MARK = ('</#noparse><img class="tn-mark" src="${url.resourcesPath}/img/teknoir-mark.svg" alt="" '
        'width="215" height="211"><#noparse>')
LOGO = ('</#noparse><img class="tn-logo" src="${url.resourcesPath}/img/teknoir-logo.svg" alt="Teknoir" '
        'width="1380" height="210"><#noparse>')
# The close talks to signed-up users: the prospect line ("Start with one robot: tnctl bootstrap ·
# teknoir.ai", unreachable on airgapped installs) becomes a user hint plus a way back to the card
# (template.ftl handles #tn-signin).
CLOSE_CTA = ('</#noparse><p class="cta">${msg("tnCloseHint")} <code>tnctl bootstrap</code></p>\n'
             '  <p class="tn-sc-signin"><a class="btn" href="#tn-signin">${msg("doLogIn")}</a></p><#noparse>')


def scope_selector(sel: str) -> str:
    sel = sel.strip()
    if sel in (":root", "html", "body"):
        return SCOPE
    if sel.startswith(("html ", "body ")):
        return SCOPE + sel[4:]
    return f"{SCOPE} {sel}"


def scope_css(css: str) -> str:
    """Prefix every selector with .tn-sc; recurse into @media/@supports, keep @keyframes as is."""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            out.append(css[i:])
            break
        head = css[i:j]
        # matching close brace
        depth, k = 1, j + 1
        while depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        lead = head[: len(head) - len(head.lstrip())]
        h = head.strip()
        if h.startswith(("@media", "@supports", "@container")):
            out.append(f"{lead}{h}{{{scope_css(body)}}}")
        elif h.startswith("@"):
            out.append(f"{lead}{h}{{{body}}}")
        else:
            # comments before the selector stay where they are
            m = re.match(r"((?:\s*/\*.*?\*/)*\s*)(.*)", h, re.S)
            pre, sels = m.group(1), m.group(2)
            out.append(lead + pre + ",".join(scope_selector(s) for s in sels.split(",")) + "{" + body + "}")
        i = k
    return "".join(out)


def main() -> int:
    if len(sys.argv) > 1:
        os.makedirs(os.path.dirname(COPY), exist_ok=True)
        if os.path.abspath(sys.argv[1]) != COPY:
            shutil.copyfile(sys.argv[1], COPY)
    src = open(COPY, encoding="utf-8").read()
    digest = hashlib.sha256(src.encode()).hexdigest()[:12]
    stamp = f"generated by scripts/sync-showcase.py from showcase/teknoir-platform.src.html (sha256 {digest}); do not edit"

    css = re.search(r"<style>(.*?)</style>", src, re.S).group(1)
    css = css.replace("/*@@FONTS@@*/", "")  # the theme's teknoir.css declares Proxima Nova
    scoped = scope_css(css)

    defs = re.search(r'<svg class="defs".*?</svg>', src, re.S).group(0)
    start = src.index('<section class="feat')
    end = src.index("</footer>") + len("</footer>")
    body = src[start:end].replace("</main>\n", "")
    body = body.replace("<!--@@MARK@@-->", MARK).replace("<!--@@LOGO@@-->", LOGO)
    cta_start = body.index('<p class="cta">')
    cta_end = body.index("</p>", cta_start) + len("</p>")
    body = body[:cta_start] + CLOSE_CTA + body[cta_end:]
    for bad in ("</#noparse>\n<#noparse>",):
        body = body.replace(bad, "\n")
    if "@@" in body:
        raise SystemExit("sync-showcase: unknown @@placeholder@@ left in the markup")

    ftl = (f"<#-- {stamp} -->\n"
           f'<div class="tn-sc" id="tn-showcase">\n<#noparse>\n{defs}\n\n{body}\n</#noparse>\n</div>\n')
    open(OUT_FTL, "w", encoding="utf-8").write(ftl)
    open(OUT_CSS, "w", encoding="utf-8").write(f"/* {stamp} */\n{scoped.strip()}\n")
    print(f"wrote {os.path.relpath(OUT_FTL, ROOT)} and {os.path.relpath(OUT_CSS, ROOT)} (source {digest})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
